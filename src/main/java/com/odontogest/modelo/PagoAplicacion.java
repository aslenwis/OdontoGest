package com.odontogest.modelo;

import com.odontogest.persistencia.conversor.DineroConverter;
import jakarta.persistence.Column;
import jakarta.persistence.Convert;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.Immutable;

import java.math.BigDecimal;

/**
 * Parte de un pago aplicada a una cuota (tabla {@code pago_aplicacion}). Inmutable: al anular el pago se resta de la
 * cuota pero la fila se conserva.
 */
@Entity
@Immutable
@Table(name = "pago_aplicacion")
@Getter
@Setter
@NoArgsConstructor
public class PagoAplicacion {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id")
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "pago_id", nullable = false)
    private Pago pago;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "cuota_id", nullable = false)
    private Cuota cuota;

    @Convert(converter = DineroConverter.class)
    @Column(name = "monto_cent", nullable = false)
    private BigDecimal monto;
}
